def build_clean_presentation_system(old_sys: str, old_user: str) -> str:
    """Dynamically build concise final presentation prompt ensuring exact hotel & price sync."""
    hotel_m = re.search(r"Выбранный отель:\s*«([^»]+)»", old_user)
    if not hotel_m:
        hotel_m = re.search(r"Выбранный отель:\s*[\"']?([^\"'\n\r]+)[\"']?", old_user)
    hotel_name = hotel_m.group(1).strip() if hotel_m else "выбранный отель"

    price_m = re.search(r"ИТОГОВАЯ СТОИМОСТЬ:\s*([\d,\s]+)\s*₽", old_user)
    if not price_m:
        price_m = re.search(r"ИТОГОВАЯ СТОИМОСТЬ:\s*([\d,\s]+)", old_user)
    total_price = price_m.group(1).strip() if price_m else ""

    is_overdraft = "превышен на" in old_sys.lower()
    is_mutation = "Это обновление уже созданного маршрута" in old_sys

    return f"""Ты — живой, прагматичный тревел-эксперт Островка (в стиле Отелло).
Напиши короткое, теплое и информативное резюме маршрута для чата (строго 2 коротких абзаца, без воды).

ЖЕСТКИЕ ПРАВИЛА СИНХРОНИЗАЦИИ С КАРТОЧКАМИ СПРАВА:
1. Назови выбранный отель точно так: «{hotel_name}». Не упоминай другие отели.
2. Укажи точную итоговую стоимость тура: **{total_price} ₽** (никогда НЕ пиши перед ценой слово «СТРОГО» капсом!).
3. Не используй технические ID (`flt-`, `trf-`, `altai-`) и шаблонные фразы («Позвольте представить», «Ваш тур полностью укомплектован», «Добро пожаловать в сказку»).
4. {"Это обновление маршрута: в первом же предложении без приветствий скажи, что именно ты обновил и как изменилась стоимость." if is_mutation else "Начинай сразу с сути подобранного маршрута без длинных приветствий."}
5. {"Бюджет превышен из-за стоимости авиаперелета — обязательно мягко используй слово «превышен» и объясни стоимость билетов." if is_overdraft else "Бюджет соблюден — категорически запрещено писать слова «бюджет превышен»."}
6. НЕ пиши в конце блок «Что могу сделать дальше» (система добавит его автоматически).

СТРУКТУРА ОТВЕТА (2 КОРОТКИХ АБЗАЦА):
- **Абзац 1 (Маршрут и почему этот отель):** Перелёт, трансфер и почему выбрали «{hotel_name}» — выдели 1–2 главных плюса конкретно под запрос туриста (например, закрытая ровная территория без ступенек, детская площадка из кедра, своя кухня или баня).
- **Абзац 2 (Честно про нюансы и бюджет):** Коротко и честно укажи компромисс отеля из `cons` (например, что завтраки не включены, но есть полная кухня, а до супермаркета 12 минут на авто) и назови общую сумму под ключ: **{total_price} ₽**.
"""


def rewrite_incoming_payload(payload: dict[str, Any]) -> dict[str, Any]:
    """Intercept and rewrite system and user prompts in incoming Gemini request payloads."""
    if not isinstance(payload, dict):
        return payload

    sys_inst = payload.get("systemInstruction")
    sys_parts: list[dict[str, Any]] = []
    sys_text = ""
    if isinstance(sys_inst, dict):
        raw_parts = sys_inst.get("parts")
        if isinstance(raw_parts, list):
            sys_parts = raw_parts
            for p in sys_parts:
                if isinstance(p, dict) and "text" in p:
                    sys_text += str(p["text"]) + "\n"
                elif isinstance(p, str):
                    sys_text += p + "\n"
    elif isinstance(sys_inst, str):
        sys_text = sys_inst

    contents = payload.get("contents")
    last_user_text = ""
    last_user_part: dict[str, Any] | None = None

    if isinstance(contents, list) and contents:
        for c in reversed(contents):
            if isinstance(c, dict):
                parts = c.get("parts")
                if isinstance(parts, list):
                    for p in reversed(parts):
                        if isinstance(p, dict) and "text" in p:
                            last_user_text = str(p["text"])
                            last_user_part = p
                            break
                        elif isinstance(p, str):
                            last_user_text = p
                            break
            if last_user_text:
                break

    # 1. Фаза 1: Анализатор интента, памяти и прямых ответов
    if "Ты — аналитик диалога и памяти" in sys_text:
        payload["systemInstruction"] = {"parts": [{"text": PHASE1_SYSTEM_PROMPT}]}
        gen_cfg = payload.get("generationConfig")
        if not isinstance(gen_cfg, dict):
            gen_cfg = {}
            payload["generationConfig"] = gen_cfg
        gen_cfg["temperature"] = 0.15

    # 2. Фаза 3 Decision: Выбор конкретного отеля из кандидатов (JSON)
    elif "КАНДИДАТЫ В ОТЕЛИ:" in last_user_text:
        payload["systemInstruction"] = {"parts": [{"text": DECISION_SYSTEM_PROMPT}]}
        warning_note = (
            "\n\nКРИТИЧЕСКОЕ ТРЕБОВАНИЕ: Если турист едет с детьми или пожилыми людьми — "
            "НЕ ВЫБИРАЙ 'Дикий таежный ретрит' (`altai-чемал-050`) с крутым каменистым спуском и без связи! "
            "Выбери 'Семейный кедровый коттедж' с ровной территорией и детской площадкой (`altai-чемал-071` или `altai-чемал-053`)!"
        )
        if "КРИТИЧЕСКОЕ ТРЕБОВАНИЕ:" not in last_user_text:
            if last_user_part is not None and "text" in last_user_part:
                last_user_part["text"] = last_user_text + warning_note
            elif contents and isinstance(contents[-1], dict):
                c_parts = contents[-1].get("parts")
                if (
                    isinstance(c_parts, list)
                    and c_parts
                    and isinstance(c_parts[0], dict)
                ):
                    c_parts[0]["text"] = last_user_text + warning_note

    # 3. Фаза 4: Финальная презентация тура в чат
    elif (
        "УТВЕРЖДЕННЫЕ ДЕТАЛИ МАРШРУТА:" in last_user_text
        or "КОМПАКТНЫЙ, лаконичный ответ" in sys_text
    ):
        new_pres_sys = build_clean_presentation_system(sys_text, last_user_text)
        payload["systemInstruction"] = {"parts": [{"text": new_pres_sys}]}
        gen_cfg = payload.get("generationConfig")
        if not isinstance(gen_cfg, dict):
            gen_cfg = {}
            payload["generationConfig"] = gen_cfg
        gen_cfg["temperature"] = 0.3

    # 4. Фаза 2: Вызов инструментов (Tools)
    elif "tools" in payload and sys_text:
        if PHASE2_SYSTEM_ADDON.strip() not in sys_text:
            payload["systemInstruction"] = {
                "parts": [{"text": sys_text.strip() + "\n" + PHASE2_SYSTEM_ADDON}]
            }

    return payload
